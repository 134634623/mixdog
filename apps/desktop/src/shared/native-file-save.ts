// Native save sink contract: the JS↔native messages the phone shells must
// implement so a paired device can write a downloaded host file
// (shared/file-downloads.ts) to device storage and share it. Android:
// `MixdogNativeHost.java` (`handle(method, args, bundledPage)`, replies are
// JSON strings). iOS: `MixdogNativeBridge.swift`
// (`userContentController(_:didReceive:replyHandler:)`). Both reach the page
// through `MixdogNativeInfo.call` (shared/native-app.ts), whose
// `MixdogNativeCalls` map includes the entries below.
//
// Rules both shells implement:
// - Capability: `getNativeCapabilities` answers `{ fileSave: 1 }`. Older shells
//   answer `null` for any unknown method, which the page reads as "no native
//   sink" (it then falls back to a browser download/share).
// - Same origin policy as every other call: only the main frame of an allowed
//   relay origin (or the bundled page) is answered; anything else gets `null`.
// - Handles are generated by the NATIVE side (≥128 random bits, base64url),
//   opaque to the page and valid only for the page/WebView that began them.
//   A page never names a file path; the native side owns the destination.
// - `begin` declares the exact byte size up front; the native side refuses
//   sizes over FILE_DOWNLOAD_MAX_BYTES and may refuse when storage is short.
//   It may show a system save/location UI (hence the longer call timeout).
// - Writes are strictly sequential: `offset` must equal the bytes durably
//   written so far, `data` is standard base64 of at most
//   NATIVE_FILE_SAVE_MAX_CHUNK_BYTES raw bytes. The page sends the next write
//   only after the previous ack (`written`), which is the backpressure.
// - `finish` succeeds only when `written === size` declared at begin; it then
//   invalidates the handle for writes and says where the file is: `persisted`
//   true when it stays saved on the device without sharing (Downloads via
//   MediaStore on Android API 29+), false when it only sits in temporary or
//   app-private staging (the iOS temp dir, the app dir on Android < 29) and is
//   kept only by sharing it. Shells that predate the field omit it; the page
//   reads that as `true`.
// - `abort` (and any failure, page unload, or the app being backgrounded long
//   enough to lose the WebView) deletes the partial file and invalidates the
//   handle. Unknown/finished handles answer `unknown-handle`.
// - `share` presents the OS share sheet for a FINISHED handle's file; it may
//   be called again (the user dismissed the sheet) until the handle expires,
//   after which it answers `unknown-handle`.
// - Errors are values (`{ ok: false, error }`), never thrown, so a bridge that
//   only returns JSON (Android) and one with reply handlers (iOS) agree.

import type { FileDownloadPurpose } from './file-downloads';

/** Feature flags a shell reports through `getNativeCapabilities`. */
export interface NativeAppCapabilities {
  /** Implements fileSaveBegin/Write/Finish/Abort/Share below. */
  fileSave?: 1;
}

/** Largest raw chunk one `fileSaveWrite` carries (base64 in the message). */
export const NATIVE_FILE_SAVE_MAX_CHUNK_BYTES = 1024 * 1024;
/** `fileSaveBegin` and `fileSaveShare` may wait on system UI. */
export const NATIVE_FILE_SAVE_INTERACTIVE_TIMEOUT_MS = 5 * 60_000;

export type NativeFileSaveErrorCode =
  /** The user dismissed the save/location or share UI. */
  | 'cancelled'
  /** Writing to device storage failed (space, I/O). */
  | 'storage'
  /** The OS denied access to the destination. */
  | 'permission'
  /** `size` over the limit, or more bytes than declared. */
  | 'too-large'
  /** A write's `offset` was not the bytes written so far. */
  | 'offset-mismatch'
  /** `finish` before every declared byte arrived. */
  | 'size-mismatch'
  /** Unknown, aborted or (for writes) finished handle. */
  | 'unknown-handle'
  /** Malformed arguments (bad base64, empty chunk, oversize chunk). */
  | 'invalid';

export type NativeFileSaveReply<T> = ({ ok: true } & T) | { ok: false; error: NativeFileSaveErrorCode };

export interface NativeFileSaveBeginArgs {
  /** Suggested file name (sanitized by the host; the shell may sanitize more). */
  name: string;
  mime: string;
  /** Exact byte count that will be written. */
  size: number;
  purpose: FileDownloadPurpose;
}

export interface NativeFileSaveBegun {
  /** Native-generated opaque handle for the writes that follow. */
  handle: string;
}

export interface NativeFileSaveWriteArgs {
  handle: string;
  /** Must equal the `written` of the previous ack (0 for the first write). */
  offset: number;
  /** Standard base64 of 1..NATIVE_FILE_SAVE_MAX_CHUNK_BYTES raw bytes. */
  data: string;
}

export interface NativeFileSaveWriteAck {
  handle: string;
  /** Bytes durably written so far (`offset` + this chunk's length). */
  written: number;
}

export interface NativeFileSaveFinishArgs {
  handle: string;
  /** The size declared at begin, restated so a mismatch fails here. */
  size: number;
}

export interface NativeFileSaveFinished {
  handle: string;
  /** Name the file was published under (the OS may de-duplicate it). */
  displayName: string;
  size: number;
  /** The file stays saved on the device without sharing; false when it only
   *  lives in staging until shared. Absent from older shells: read as true. */
  persisted?: boolean;
}

export interface NativeFileSaveHandleArgs {
  handle: string;
}

export interface NativeFileShared {
  /** false when the user dismissed the sheet without sharing. */
  shared: boolean;
}

/** Entries merged into `MixdogNativeCalls` (shared/native-app.ts). Each reply
 *  may also be `null` from a shell that predates the method. */
export interface NativeFileSaveCalls {
  getNativeCapabilities: [undefined, NativeAppCapabilities | null];
  fileSaveBegin: [NativeFileSaveBeginArgs, NativeFileSaveReply<NativeFileSaveBegun> | null];
  fileSaveWrite: [NativeFileSaveWriteArgs, NativeFileSaveReply<NativeFileSaveWriteAck> | null];
  fileSaveFinish: [NativeFileSaveFinishArgs, NativeFileSaveReply<NativeFileSaveFinished> | null];
  fileSaveAbort: [NativeFileSaveHandleArgs, NativeFileSaveReply<NativeFileSaveHandleArgs> | null];
  fileSaveShare: [NativeFileSaveHandleArgs, NativeFileSaveReply<NativeFileShared> | null];
}

/** Calls that may wait on system UI and so get the interactive timeout. */
export const NATIVE_FILE_SAVE_INTERACTIVE_CALLS: ReadonlySet<keyof NativeFileSaveCalls> = new Set([
  'fileSaveBegin',
  'fileSaveShare',
]);
